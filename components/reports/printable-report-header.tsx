"use client";

import React from "react";
import { escapeHtml } from "@/lib/reports/erp-report-template-builder";
import { useActiveLanguage } from "@/lib/i18n/use-active-language";
import { autoTranslate5Languages } from "@/lib/i18n/multilingual-translator";

export interface PrintableReportHeaderProps {
  documentTitle: string;
  documentSubtitle?: string;
  documentNo?: string;
  scopeCountry?: string;
  scopeBranch?: string;
  scopeCurrency?: string;
  dateRange?: string;
  userName?: string;
  filtersSummary?: string;
  /** Resolved branding — no hard-coded company identity. */
  companyName?: string;
  productName?: string;
  companyAddress?: string;
  companyTaxNo?: string;
  companyContact?: string;
}

export function PrintableReportHeader({
  documentTitle,
  documentSubtitle,
  documentNo,
  scopeCountry = "All Countries",
  scopeBranch = "All Branches",
  scopeCurrency = "",
  dateRange = "All Available Records",
  userName = "—",
  filtersSummary,
  companyName = "",
  productName = "Digital Dock ERP",
  companyAddress = "",
  companyTaxNo = "",
  companyContact = ""
}: PrintableReportHeaderProps) {
  const lang = useActiveLanguage() as "en" | "ur" | "ar" | "fa" | "ps";
  const tr = (str: string) => {
    if (!str) return str;
    const res = autoTranslate5Languages(str);
    return res[lang] || str;
  };

  const printDate = new Date();
  const printDateFormatted = printDate.toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" });
  const printTimeFormatted = printDate.toLocaleTimeString([], { hour: "2-digit", minute: "2-digit", hour12: true });
  const fullDateTime = `${printDateFormatted}, ${printTimeFormatted}`;

  return (
    <div className="hidden print:block w-full mb-4 pb-3 border-b-2 border-slate-900">
      <div className="flex justify-between items-start">
        {/* Company Branding Left */}
        <div className="w-[55%]">
          {companyName && (
            <div className="text-lg font-black text-slate-950 uppercase tracking-tight">
              {companyName}
            </div>
          )}
          {productName && (
            <div className="text-[10px] font-bold text-slate-500 uppercase tracking-wider">
              {productName}
            </div>
          )}
          {(companyAddress || companyTaxNo || companyContact) && (
            <div className="text-[9px] text-slate-600 mt-1 leading-tight">
              {companyAddress && <>{companyAddress}<br /></>}
              {[companyTaxNo, companyContact].filter(Boolean).join(" | ")}
            </div>
          )}
        </div>

        {/* Document Title & Scope Right */}
        <div className="w-[45%] text-right">
          <div className="text-sm font-black text-blue-900 uppercase tracking-wide">
            {tr(documentTitle)}
          </div>
          {documentSubtitle && (
            <div className="text-[10px] font-bold text-slate-600">
              {tr(documentSubtitle)}
            </div>
          )}
          <div className="text-[9px] text-slate-600 mt-1 leading-relaxed">
            {documentNo && <div><strong>{tr("Document No")}:</strong> {documentNo}</div>}
            <div><strong>{tr("Generated By")}:</strong> {userName}</div>
            <div><strong>{tr("Generated Date & Time")}:</strong> {fullDateTime}</div>
            <div className="inline-block bg-slate-100 border border-slate-300 px-2 py-0.5 rounded text-[8px] font-bold text-slate-900 mt-1">
              {tr("Scope")}: {scopeCountry} | {scopeBranch} | {scopeCurrency}
            </div>
          </div>
        </div>
      </div>

      {/* Optional Filter Parameters Bar */}
      {(dateRange || filtersSummary) && (
        <div className="mt-2 pt-1.5 border-t border-slate-200 flex justify-between text-[8.5px] font-semibold text-slate-700">
          <div><strong>{tr("Date Range")}:</strong> {dateRange}</div>
          {filtersSummary && <div><strong>{tr("Filters")}:</strong> {filtersSummary}</div>}
          <div><strong>{tr("Base Currency")}:</strong> {scopeCurrency}</div>
        </div>
      )}
    </div>
  );
}
