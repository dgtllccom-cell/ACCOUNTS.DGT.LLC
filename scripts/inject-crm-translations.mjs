for (const [langKey, dict] of Object.entries(crmTranslations)) {
  const marker = `${langKey}: {`;
  const idx = content.indexOf(marker);
  if (idx !== -1) {
    const insertPos = idx + marker.length;
    let newEntries = "\n";
    for (const [k, v] of Object.entries(dict)) {
      newEntries += `    "${k}": "${v.replace(/"/g, '\\"')}",\n`;
    }
    content = content.slice(0, insertPos) + newEntries + content.slice(insertPos);
    console.log(`Injected ${Object.keys(dict).length} CRM keys for ${langKey}`);
  }
}

fs.writeFileSync(filePath, content, 'utf8');
