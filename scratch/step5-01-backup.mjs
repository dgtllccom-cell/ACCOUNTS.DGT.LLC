import fs from "node:fs";
import { execSync } from "node:child_process";
const PROD = fs.readFileSync("scripts/backup-vps-db.mjs","utf8").match(/postgresql:\/\/[^\s'"]+/)[0];
const stamp = new Date().toISOString().replace(/[:.]/g,"-");
const out = `backups/PROD-pre-reconcile-${stamp}`;
console.log("STEP 5.1 — fresh PRODUCTION backup → " + out);
execSync(`node scripts/db-backup-engine.mjs --output "${out}"`, { stdio: "inherit", env: { ...process.env, DATABASE_URL: PROD } });
const m = JSON.parse(fs.readFileSync(`${out}/manifest.json`,"utf8"));
const tbls = Object.entries(m.tables);
const done = tbls.filter(([,v])=>v.status==="complete").length;
const rows = tbls.reduce((s,[,v])=>s+(v.count||0),0);
const files = fs.readdirSync(out);
const mb = (files.reduce((s,f)=>s+fs.statSync(`${out}/${f}`).size,0)/1048576).toFixed(1);
console.log(`\n[VERIFY] tables: ${tbls.length} (complete: ${done}) | rows: ${rows} | files: ${files.length} | size: ${mb} MB`);
const key = ["purchase_orders","purchase_order_payments","roznamcha_entries","roznamcha_lines","ledgers","employees","customers","profiles","permissions","user_role_assignments"];
console.log("[VERIFY] key tables:", key.map(t=>`${t}=${m.tables[t]?.count ?? "?"}`).join(" "));
const ok = tbls.length>=185 && done===tbls.length && Number(mb)>1;
console.log(ok ? "\n✅ BACKUP VERIFIED" : "\n❌ BACKUP SUSPECT — STOP");
if (!ok) process.exit(1);
fs.writeFileSync("scratch/step5-backup-path.txt", out);
